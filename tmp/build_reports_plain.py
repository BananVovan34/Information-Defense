def plain(s):
    return html.unescape(re.sub(r'<[^>]+>', '', s.replace('<br/>', ' / ')))

def duration(seconds):
    n = int(round(seconds))
    d, n = divmod(n, 86400)
    h, n = divmod(n, 3600)
    m, s = divmod(n, 60)
    return ' '.join(x for x in [f'{d} сут' if d else '', f'{h} ч' if h else '', f'{m} мин' if m else '', f'{s} с' if s else ''] if x)

def number(n):
    return f'{n:,}'.replace(',', ' ')

class Report:
    def __init__(self, pdf, md):
        self.pdf, self.md = pdf, md
        self.story, self.text = [], []

    def p(self, text, style='body'):
        self.story.append(Paragraph(text, ST[style]))
        self.text.extend([plain(text), ''])

    def title(self, lab, topic):
        self.p(lab, 'title')
        self.p(topic, 'topic')
        self.text[0] = '# ' + lab

    def h(self, text, question=False):
        self.p(text, 'q' if question else 'h')
        self.text[-2] = '## ' + text

    def page(self):
        self.story.append(PageBreak())

    def figure(self, path, caption, width):
        path = Path(path)
        with PILImage.open(path) as image:
            w, h = image.size
        image = Image(str(path), width=width*mm, height=width*mm*h/w)
        image.hAlign = 'CENTER'
        self.story.append(KeepTogether([image, Paragraph(caption, ST['caption'])]))
        self.text.extend([f'![{caption}](<{path.as_posix()}>)', ''])

    def table(self, headers, rows, widths):
        content = [[Paragraph(x, ST['cellhead']) for x in headers]]
        content += [[Paragraph(str(x), ST['cell']) for x in row] for row in rows]
        table = Table(content, colWidths=widths, repeatRows=1, hAlign='LEFT')
        table.setStyle(TableStyle([
            ('GRID', (0,0), (-1,-1), .4, colors.HexColor('#999999')),
            ('VALIGN', (0,0), (-1,-1), 'TOP'),
            ('LEFTPADDING', (0,0), (-1,-1), 5), ('RIGHTPADDING', (0,0), (-1,-1), 5),
            ('TOPPADDING', (0,0), (-1,-1), 5), ('BOTTOMPADDING', (0,0), (-1,-1), 5),
        ]))
        self.story.extend([table, Spacer(1, 7)])
        self.text.extend(['| ' + ' | '.join(map(plain, headers)) + ' |', '|'+'|'.join(['---']*len(headers))+'|'])
        self.text.extend('| '+' | '.join(plain(str(x)) for x in row)+' |' for row in rows)
        self.text.append('')

    def build(self):
        self.md.parent.mkdir(parents=True, exist_ok=True)
        doc = SimpleDocTemplate(str(self.pdf), pagesize=A4,
            leftMargin=17*mm, rightMargin=17*mm, topMargin=14*mm, bottomMargin=14*mm,
            title=self.text[0].lstrip('# '), author='')
        def footer(canvas, doc):
            canvas.saveState()
            canvas.setFont('Times', 10)
            canvas.drawCentredString(A4[0]/2, 7.5*mm, str(doc.page))
            canvas.restoreState()
        doc.build(self.story, onFirstPage=footer, onLaterPages=footer)
        self.md.write_text('\n'.join(self.text), encoding='utf-8')
        return self.pdf

